#!/usr/bin/env bash
# Report the cross-host watch and what it last saw on the 4090.
set -euo pipefail
SCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
source "${SCRIPT_DIR}/common.sh"

if [[ ! -s "${REMOTE_PID_FILE}" ]]; then
  echo "Remote dashboard supervisor: stopped" >&2
  exit 1
fi
pid=""
read -r pid <"${REMOTE_PID_FILE}" || true
if [[ ! "${pid}" =~ ^[0-9]+$ ]] || ! kill -0 "${pid}" 2>/dev/null; then
  echo "Remote dashboard supervisor: stopped (stale pid file)" >&2
  exit 1
fi
if [[ ! -s "${REMOTE_STATUS_FILE}" ]]; then
  echo "Remote dashboard supervisor: starting (no completed cycle yet)" >&2
  exit 1
fi

# The file is generated by remote-supervisor-loop.sh with shell-escaped values.
source "${REMOTE_STATUS_FILE}"
now_epoch="$(date +%s)"
if [[ ! "${checked_epoch:-}" =~ ^[0-9]+$ ]] || \
   (( now_epoch - checked_epoch > REMOTE_MAX_STATUS_AGE_SECONDS )); then
  echo "Remote dashboard supervisor: stale status (last cycle ${checked_at:-unknown})" >&2
  exit 1
fi
if [[ "${result:-unreachable}" != "ok" ]]; then
  echo "Remote dashboard supervisor: ${result:-unreachable} at ${checked_at:-unknown}" >&2
  echo "Log: ${REMOTE_LOG_FILE}" >&2
  exit 1
fi

echo "Remote dashboard supervisor: healthy"
echo "Pid: ${pid}"
echo "Last cycle: ${checked_at}"
echo "Target: ${target:-unknown} (4090 supervisor alive)"
