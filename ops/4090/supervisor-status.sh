#!/usr/bin/env bash
# Report whether the host-level tmux supervisor is alive and what it last saw.
set -euo pipefail
SCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
source "${SCRIPT_DIR}/common.sh"

if [[ ! -s "${SUPERVISOR_PID_FILE}" ]]; then
  echo "Dashboard host supervisor: stopped" >&2
  exit 1
fi
pid=""
read -r pid <"${SUPERVISOR_PID_FILE}" || true
if [[ ! "${pid}" =~ ^[0-9]+$ ]] || ! kill -0 "${pid}" 2>/dev/null; then
  echo "Dashboard host supervisor: stopped (stale pid file)" >&2
  exit 1
fi
if [[ ! -s "${SUPERVISOR_STATUS_FILE}" ]]; then
  echo "Dashboard host supervisor: starting (no completed cycle yet)" >&2
  exit 1
fi

# The file is generated by supervisor-loop.sh with shell-escaped values only.
source "${SUPERVISOR_STATUS_FILE}"
now_epoch="$(date +%s)"
if [[ ! "${checked_epoch:-}" =~ ^[0-9]+$ ]] || \
   (( now_epoch - checked_epoch > SUPERVISOR_MAX_STATUS_AGE_SECONDS )); then
  echo "Dashboard host supervisor: stale status (last cycle ${checked_at:-unknown})" >&2
  exit 1
fi
if [[ "${result:-failed}" == "deploying" ]]; then
  echo "Dashboard host supervisor: a deployment is running; sessions left to it (${checked_at:-unknown})" >&2
  echo "Log: ${SUPERVISOR_LOG_FILE}" >&2
  exit 1
fi
if [[ "${result:-failed}" != "ok" ]]; then
  echo "Dashboard host supervisor: ${result:-failed} at ${checked_at:-unknown}" >&2
  echo "Missing sessions: ${missing_sessions:-unknown}" >&2
  echo "Log: ${SUPERVISOR_LOG_FILE}" >&2
  exit 1
fi

echo "Dashboard host supervisor: healthy"
echo "Pid: ${pid}"
echo "Last cycle: ${checked_at}"
echo "Guarded sessions: ${sessions_present}/${sessions_total} present"
