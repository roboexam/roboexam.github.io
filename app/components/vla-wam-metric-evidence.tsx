import { Pi05CuratedEvidence } from "./pi05-curated-evidence";
import { vlaWamDashboardBundle } from "../data/vla-wam-results";
import { VlaWamSampleEvidence } from "./vla-wam-sample-evidence";
import { Xvla24IdEvidence } from "./xvla-24id-evidence";
import type { XvlaSetting } from "../data/xvla-24id";

export function VlaWamMetricEvidence({ id, model, formula, taskId, setting = "id" }: { id: string; model: string; formula: string; taskId?: string; setting?: XvlaSetting }) {
  if (model === "Pi0.5" && taskId) return <Pi05CuratedEvidence key={`${taskId}:${id}`} taskId={taskId} metricId={id} formula={formula}/>;
  if (model === "XVLA" && taskId) return <Xvla24IdEvidence key={`${taskId}:${setting}:${id}`} taskId={taskId} metricId={id} formula={formula} setting={setting}/>;
  const modelResult = vlaWamDashboardBundle.models[model];
  const metric = modelResult?.values[id];
  if (!modelResult) return null;

  const cohort = modelResult.cohort;
  return <><VlaWamSampleEvidence id={id} model={model} formula={formula}/>{metric && <section className="formalEvidence" aria-label={`${model} ${id} formal aggregate evidence`}>
    <div className="formalEvidenceHeader">
      <div>
        <span>FORMAL AGGREGATE EVIDENCE</span>
        <h3>{model} · {modelResult.task}</h3>
        <p>{modelResult.resultVersion}</p>
      </div>
      <div className={metric.availability === "available" ? "formalEvidenceValue" : "formalEvidenceValue unavailable"}>
        <strong>{metric.primary}</strong>
        <span>{id === "AC" ? "Outcome, trajectory, and metadata verified" : metric.aux}</span>
      </div>
    </div>
    <div className="formalEvidenceFacts">
      <article><span>Cohort</span><strong>{cohort.episodes} episodes</strong><p>{cohort.uniqueSeeds} distinct seeds</p></article>
      <article><span>Outcome</span><strong>{cohort.success} / {cohort.partial} / {cohort.failure}</strong><p>success / partial / failure</p></article>
      <article><span>Evaluator</span><strong>v{modelResult.pipelineVersion}</strong><p>{modelResult.protocol}</p></article>
      <article><span>Provenance</span><strong>{modelResult.provenance.summarySha256.slice(0, 12)}</strong><p>formal summary SHA-256</p></article>
    </div>
    <p className="formalEvidenceNote">This value is generated by the allowlisted exporter from the formal evaluator summary. The browser bundle contains no server paths. Real zero values remain computed; missing evidence stays N/A.</p>
  </section>}</>;
}
